"""House back-porch STAND-INS (2026-09-24): the forest bed, the window bursting, the guillotine,
the watermelon, the three forest ghosts and the witch.

    python3 tools/make_sfx_house_porch.py
    /Applications/Godot.app/Contents/MacOS/Godot --headless --path game --import

⚠️ These are PLACEHOLDERS. The user will supply real recordings; `docs/TODO_sounds.md`
("2026-09-24 — House porch pass (stand-ins)") carries the prompt for each. When a real file
arrives, delete that name from SOUNDS below (or drop the file over the .wav with the same base
name) — do NOT re-run this tool afterwards without doing so, or it silently overwrites the
real recording.

Pure stdlib, 44.1 kHz 16-bit mono, one seeded RNG PER SOUND (so adding a twelfth sound never
changes the other eleven — the make_sfx_backrooms.py lesson). Base names checked globally
unique on 2026-09-24 (`GameState.load_audio()` resolves by base name across every subdir).

Voices (the scream, the screech, the howl, the hum) are ADDITIVE: each harmonic of a moving
f0 is weighted by a formant envelope evaluated at that harmonic's frequency, which is a
source-filter voice without a filter's stability problems. Harshness is tanh.

`window_burst` layers the shared `glass_break.wav` under a synthesised shard tail when that
file exists (it is not generated by any tool here, so re-running is still deterministic).

Level targets (peak dBFS): stings -3, 3D one-shots -4..-6, the loop bed -12, the hum -10.
Every file prints its peak, RMS and loudest-300 ms, which is what a caller's volume_db should
be set from — never from a plausible number.
"""

import math
import os
import random
import struct
import wave

SR = 44100
ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
OUT_DIR = os.path.join(ROOT, "game", "assets", "audio", "level_2_house")
GLASS = os.path.join(ROOT, "game", "assets", "audio", "shared", "glass_break.wav")
TAU = 2.0 * math.pi


# ----------------------------------------------------------------------------- primitives
def buf(seconds):
    return [0.0] * int(SR * seconds)


def env_ad(t, a, d):
    return (t / a) if t < a else math.exp(-(t - a) / d)


def add(out, start, fn, length):
    s0 = int(start * SR)
    for i in range(int(length * SR)):
        j = s0 + i
        if 0 <= j < len(out):
            out[j] += fn(i / SR)


def lowpass(x, fc):
    a = 1.0 - math.exp(-TAU * fc / SR)
    y, out = 0.0, []
    for v in x:
        y += a * (v - y)
        out.append(y)
    return out


def highpass(x, fc):
    lp = lowpass(x, fc)
    return [a - b for a, b in zip(x, lp)]


class BandPass:
    """RBJ band-pass (0 dB peak), coefficients settable per block."""

    def __init__(self):
        self.x1 = self.x2 = self.y1 = self.y2 = 0.0
        self.set(1000.0, 1.0)

    def set(self, fc, q):
        fc = max(20.0, min(fc, SR * 0.45))
        w = TAU * fc / SR
        alpha = math.sin(w) / (2 * q)
        a0 = 1 + alpha
        self.b0, self.b2 = alpha / a0, -alpha / a0
        self.a1, self.a2 = -2 * math.cos(w) / a0, (1 - alpha) / a0

    def __call__(self, x):
        y = self.b0 * x + self.b2 * self.x2 - self.a1 * self.y1 - self.a2 * self.y2
        self.x2, self.x1 = self.x1, x
        self.y2, self.y1 = self.y1, y
        return y


def sweep_bp(x, fc_of_t, q):
    bp = BandPass()
    out = []
    for i, v in enumerate(x):
        if i % 32 == 0:
            bp.set(fc_of_t(i / SR), q)
        out.append(bp(v))
    return out


def formant_gain(f, formants):
    """Sum of resonance bumps: formants = [(centre Hz, bandwidth Hz, gain)]."""
    g = 0.0
    for fc, bw, amp in formants:
        d = (f - fc) / (bw * 0.5)
        g += amp / (1.0 + d * d)
    return g


def voice(seconds, f0_of_t, formants_of_t, amp_of_t, max_hz=9000.0, jitter=0.0, rng=None,
          block=64):
    """Additive source-filter voice. f0/formants/amp are functions of time."""
    n = int(SR * seconds)
    out = [0.0] * n
    phase = 0.0
    weights = []
    jit = 0.0
    for i in range(n):
        t = i / SR
        if i % block == 0:
            f0 = f0_of_t(t)
            if rng is not None and jitter:
                jit = jit * 0.7 + rng.uniform(-1, 1) * jitter * 0.3
            f0 *= 1.0 + jit
            forms = formants_of_t(t)
            k_max = max(1, int(max_hz / max(f0, 1.0)))
            weights = [formant_gain(k * f0, forms) / math.sqrt(k) for k in range(1, k_max + 1)]
            step = TAU * f0 / SR
        phase += step
        s = 0.0
        for k, w in enumerate(weights, 1):
            s += w * math.sin(k * phase)
        out[i] = s * amp_of_t(t)
    return out


def comb_reverb(x, mix, decay_s, tail_s=0.0):
    """Tiny Schroeder: four combs + two all-passes. `tail_s` extends the buffer."""
    x = x + [0.0] * int(SR * tail_s)
    delays = [1557, 1617, 1491, 1422]
    wet = [0.0] * len(x)
    for d in delays:
        g = 10 ** (-3.0 * d / SR / decay_s)
        line = [0.0] * d
        idx = 0
        for i, v in enumerate(x):
            y = line[idx]
            line[idx] = v + y * g
            idx = (idx + 1) % d
            wet[i] += y * 0.25
    for d, g in ((225, 0.5), (556, 0.5)):
        line = [0.0] * d
        idx = 0
        for i, v in enumerate(wet):
            b = line[idx]
            y = -g * v + b
            line[idx] = v + g * y
            idx = (idx + 1) % d
            wet[i] = y
    return [a * (1 - mix) + b * mix for a, b in zip(x, wet)]


def saturate(x, drive):
    return [math.tanh(v * drive) for v in x]


def fade(x, fin, fout):
    n = len(x)
    a, b = int(fin * SR), int(fout * SR)
    for i in range(a):
        x[i] *= i / a
    for i in range(b):
        x[n - 1 - i] *= i / b
    return x


def measure(x):
    peak = max(abs(v) for v in x) or 1e-9
    rms = math.sqrt(sum(v * v for v in x) / len(x)) or 1e-9
    w = int(0.3 * SR)
    best = 0.0
    step = w // 4
    for s in range(0, max(1, len(x) - w), step):
        seg = x[s:s + w]
        best = max(best, sum(v * v for v in seg) / len(seg))
    return 20 * math.log10(peak), 20 * math.log10(rms), 10 * math.log10(best or 1e-18)


def write(name, x, peak_db):
    peak = max(abs(v) for v in x) or 1e-9
    g = 10 ** (peak_db / 20.0) / peak
    y = [max(-1.0, min(1.0, v * g)) for v in x]
    path = os.path.join(OUT_DIR, name)
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(b"".join(struct.pack("<h", int(v * 32767)) for v in y))
    p, r, l3 = measure(y)
    print("%-26s %5.2fs  peak %6.1f  RMS %6.1f  loudest-300ms %6.1f dBFS" % (name, len(y) / SR, p, r, l3))


def read_wav(path):
    with wave.open(path, "rb") as w:
        assert w.getsampwidth() == 2 and w.getframerate() == SR, path
        ch = w.getnchannels()
        raw = w.readframes(w.getnframes())
    vals = struct.unpack("<%dh" % (len(raw) // 2), raw)
    return [sum(vals[i:i + ch]) / (ch * 32768.0) for i in range(0, len(vals), ch)]


